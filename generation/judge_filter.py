#!/usr/bin/env python3
"""
judge_filter.py — LLM-as-a-Judge filtering for all generated tasks.

Applies pointwise scoring on three dimensions (1-5 each) to every task:
  - input_coherence         : Is the context internally consistent and realistic?
  - ground_truth_verifiability : Can a script score this task without human judgment?
  - rubric_clarity          : Is each rubric dimension unambiguous?

Tasks with mean judge score < 3.5 are filtered out.

Leakage prevention: judge_model MUST differ from generation_model.
  - Tasks generated by gemini/gemini-2.5-flash  → judged by deepseek/deepseek-chat (cross-family)
  - Tasks generated by deepseek/deepseek-chat   → judged by gemini/gemini-2.5-flash (cross-family)
  - Tasks generated by template/programmatic/trace → judged by deepseek/deepseek-chat (cheap)

Judge prompt: generation/prompts/judge_system_prompt.md
Mock mode: heuristic checks replace LLM calls (for local runs, no API key needed).

Usage:
  python generation/judge_filter.py --mock           # heuristic scoring
  python generation/judge_filter.py --live           # LLM judge (requires API key)
  python generation/judge_filter.py --mock --verbose # show per-task scores
  python generation/judge_filter.py --mock --seed 0  # override reproducibility seed
"""

import json
import argparse
import random
import sys
import re
import os
import urllib.request
from pathlib import Path

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT / "generation"))


def _load_env():
    env_file = ROOT / ".env"
    if env_file.exists():
        for line in env_file.read_text().splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                if k.strip() not in os.environ:
                    os.environ[k.strip()] = v.strip()

_load_env()

RAW_DIR      = ROOT / "generation" / "raw_tasks"
OUT_FILE     = ROOT / "generation" / "raw_tasks" / "filtered.jsonl"
LOG_FILE     = ROOT / "generation" / "raw_tasks" / "judge_filter_log.jsonl"
PROMPTS_DIR  = ROOT / "generation" / "prompts"
FILTER_THRESHOLD = 3.5

# Tier separation: dev-tier for bulk filtering, eval-tier only for calibration spot-checks.
# Dev-tier (cheap/fast): used on all tasks. Eval-tier (independent family): used on a random
# CALIBRATION_SAMPLE_RATE fraction to verify the dev-tier filter is not systematically wrong.
DEV_TIER_MODEL        = "gemini/gemini-2.5-flash"   # bulk filtering — all tasks
EVAL_TIER_MODEL       = "deepseek/deepseek-chat"     # calibration only — different family
CALIBRATION_SAMPLE_RATE = 0.10                        # 10% of passed tasks re-judged by eval-tier
CALIBRATION_AGREE_THRESHOLD = 0.80                    # flag run if agreement < 80%
CALIBRATION_LOG_FILE  = ROOT / "generation" / "raw_tasks" / "calibration_log.jsonl"

VALID_CHECKERS = {
    "signal_grounding_fn", "tone_checker_fn", "banned_phrase_fn",
    "cta_checker_fn", "word_count_fn", "pricing_mention_fn", "objection_ack_fn",
}

JUDGE_ROUTING = {
    # Cross-family leakage prevention: generator ≠ judge family
    "gemini/gemini-2.5-flash": "deepseek/deepseek-chat",      # Gemini → DeepSeek
    "deepseek/deepseek-chat":  "gemini/gemini-2.5-flash",      # DeepSeek → Gemini
    # Template/programmatic/trace: cheap DeepSeek judge, no leakage risk
    "template_expansion":      "deepseek/deepseek-chat",
    "trace_derived":           "deepseek/deepseek-chat",
    "programmatic":            "deepseek/deepseek-chat",
    "multi_llm":               "deepseek/deepseek-chat",
}

def _load_prompt(filename: str) -> str:
    path = PROMPTS_DIR / filename
    if not path.exists():
        raise FileNotFoundError(f"Prompt file not found: {path}")
    return path.read_text().strip()

JUDGE_SYSTEM_PROMPT = _load_prompt("judge_system_prompt.md")


# ── Mock heuristic judge ──────────────────────────────────────────────────────

def mock_judge(task: dict) -> dict:
    """Score task heuristically without LLM calls."""
    scores = {}

    # input_coherence: context length + signal present
    ctx = task["input"].get("context", "")
    has_signal = any(k in ctx.lower() for k in [
        "series", "funding", "layoff", "job posting", "posted a", "raised $",
        "cut ", "headcount", "q1", "q2", "q3", "q4", "2025", "2026"
    ])
    ctx_words = len(ctx.split())
    if ctx_words >= 40 and has_signal:
        scores["input_coherence"] = 5
    elif ctx_words >= 20:
        scores["input_coherence"] = 4 if has_signal else 3
    else:
        scores["input_coherence"] = 2

    # ground_truth_verifiability: all checkers in VALID_CHECKERS + constraints are concrete
    dims = task["ground_truth"]["dimensions"]
    all_valid_checkers = all(d["checker"] in VALID_CHECKERS for d in dims.values())
    weights_sum = abs(sum(d["weight"] for d in dims.values()) - 1.0)
    has_word_constraint = any(re.search(r'under \d+', c, re.I)
                               for c in task["input"].get("constraints", []))
    if all_valid_checkers and weights_sum < 0.01 and has_word_constraint:
        scores["ground_truth_verifiability"] = 5
    elif all_valid_checkers and weights_sum < 0.01:
        scores["ground_truth_verifiability"] = 4
    elif all_valid_checkers:
        scores["ground_truth_verifiability"] = 3
    else:
        scores["ground_truth_verifiability"] = 2

    # rubric_clarity: all dimensions have non-empty descriptions
    all_have_desc = all(d.get("description", "") for d in dims.values())
    n_dims = len(dims)
    if all_have_desc and n_dims >= 4:
        scores["rubric_clarity"] = 5
    elif all_have_desc:
        scores["rubric_clarity"] = 4
    else:
        scores["rubric_clarity"] = 3

    return scores


# ── Live LLM judge ────────────────────────────────────────────────────────────

def _judge_call_gemini(task_summary: str) -> str:
    """Call Gemini Flash as judge. Returns raw text."""
    try:
        from google import genai
        from google.genai import types as genai_types
    except ImportError:
        raise ImportError("google-genai not installed. Run: pip install google-genai")
    api_key = os.environ.get("GOOGLE_API_KEY")
    if not api_key:
        raise EnvironmentError("GOOGLE_API_KEY not set")
    client = genai.Client(api_key=api_key)
    import time
    for attempt in range(3):
        try:
            response = client.models.generate_content(
                model="gemini-2.5-flash",
                contents=f"Task to evaluate:\n{task_summary}",
                config=genai_types.GenerateContentConfig(
                    system_instruction=JUDGE_SYSTEM_PROMPT,
                    temperature=0.0,
                    max_output_tokens=100,
                    thinking_config=genai_types.ThinkingConfig(thinking_budget=0),
                ),
            )
            return response.text.strip()
        except Exception as e:
            if attempt < 2 and ("503" in str(e) or "UNAVAILABLE" in str(e) or "429" in str(e)):
                time.sleep(10 * (attempt + 1))
                continue
            raise


def _judge_call_openrouter(model_id: str, task_summary: str) -> str:
    """Call a cheap model via OpenRouter as judge. Returns raw text."""
    api_key = os.environ.get("OPENROUTER_API_KEY")
    if not api_key:
        raise EnvironmentError("OPENROUTER_API_KEY not set")
    payload = json.dumps({
        "model": model_id,
        "messages": [
            {"role": "system", "content": JUDGE_SYSTEM_PROMPT},
            {"role": "user",   "content": f"Task to evaluate:\n{task_summary}"},
        ],
        "max_tokens": 50,
        "temperature": 0.0,
    }).encode()
    req = urllib.request.Request(
        "https://openrouter.ai/api/v1/chat/completions",
        data=payload,
        headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=30) as resp:
        data = json.loads(resp.read())
    return data["choices"][0]["message"]["content"].strip()


def live_judge(task: dict, judge_model: str) -> dict:
    """Score task using LLM judge (Gemini Flash or OpenRouter). Returns scores dict."""
    task_summary = json.dumps({
        "context": task["input"]["context"][:300],
        "task_type": task["input"]["task_type"],
        "constraints": task["input"]["constraints"],
        "rubric_dims": list(task["ground_truth"]["dimensions"].keys()),
        "checkers": [d["checker"] for d in task["ground_truth"]["dimensions"].values()],
    }, indent=2)
    try:
        if judge_model.startswith("gemini/"):
            text = _judge_call_gemini(task_summary)
        else:
            text = _judge_call_openrouter(judge_model, task_summary)

        match = re.search(
            r'SCORES:\s*input_coherence=(\d),\s*ground_truth_verifiability=(\d),\s*rubric_clarity=(\d)',
            text,
        )
        if match:
            return {
                "input_coherence": int(match.group(1)),
                "ground_truth_verifiability": int(match.group(2)),
                "rubric_clarity": int(match.group(3)),
            }
        return mock_judge(task)
    except Exception as e:
        print(f"  [WARN] Live judge error for {task['task_id']}: {e} — using mock", file=sys.stderr)
        return mock_judge(task)


# ── Routing helper ────────────────────────────────────────────────────────────

def get_judge_model(task: dict) -> str:
    gen_model = task["metadata"].get("generation_model", "unknown")
    return JUDGE_ROUTING.get(gen_model, "deepseek/deepseek-chat")


# ── Calibration spot-check ────────────────────────────────────────────────────

def run_calibration(passed_tasks: list, mock: bool, seed: int = 42) -> dict:
    """Re-judge a random sample of passed tasks using EVAL_TIER_MODEL.

    Compares pass/fail decisions between DEV_TIER_MODEL (bulk) and EVAL_TIER_MODEL
    (spot-check). Logs per-task agreement and flags the run if overall agreement
    falls below CALIBRATION_AGREE_THRESHOLD.

    Returns a summary dict logged to calibration_log.jsonl.
    """
    random.seed(seed + 1)  # different seed from main filter for independent sampling
    n_sample = max(1, int(len(passed_tasks) * CALIBRATION_SAMPLE_RATE))
    sample = random.sample(passed_tasks, min(n_sample, len(passed_tasks)))

    print(f"\n[calibration] eval-tier spot-check: n={len(sample)} "
          f"({CALIBRATION_SAMPLE_RATE:.0%} of {len(passed_tasks)} passed tasks)")
    print(f"  dev-tier model : {DEV_TIER_MODEL}")
    print(f"  eval-tier model: {EVAL_TIER_MODEL}")

    agree_count = 0
    cal_logs = []
    for task in sample:
        dev_mean  = task["metadata"].get("judge_mean", 0.0)
        dev_pass  = dev_mean >= FILTER_THRESHOLD

        eval_scores = (mock_judge(task) if mock
                       else live_judge(task, EVAL_TIER_MODEL))
        eval_mean  = sum(eval_scores.values()) / len(eval_scores)
        eval_pass  = eval_mean >= FILTER_THRESHOLD
        agrees     = dev_pass == eval_pass
        if agrees:
            agree_count += 1

        cal_logs.append({
            "task_id":    task["task_id"],
            "dev_mean":   round(dev_mean, 3),
            "eval_mean":  round(eval_mean, 3),
            "dev_pass":   dev_pass,
            "eval_pass":  eval_pass,
            "agree":      agrees,
        })

    agreement_rate = agree_count / len(sample) if sample else 1.0
    status = "PASS" if agreement_rate >= CALIBRATION_AGREE_THRESHOLD else "FLAG"
    summary = {
        "n_sampled":      len(sample),
        "n_agree":        agree_count,
        "agreement_rate": round(agreement_rate, 3),
        "threshold":      CALIBRATION_AGREE_THRESHOLD,
        "status":         status,
        "dev_tier":       DEV_TIER_MODEL,
        "eval_tier":      EVAL_TIER_MODEL,
        "tasks":          cal_logs,
    }

    CALIBRATION_LOG_FILE.parent.mkdir(parents=True, exist_ok=True)
    with open(CALIBRATION_LOG_FILE, "w") as f:
        f.write(json.dumps(summary) + "\n")

    print(f"  Agreement: {agree_count}/{len(sample)} ({agreement_rate:.0%}) — {status}")
    if status == "FLAG":
        print(f"  [WARN] Calibration below {CALIBRATION_AGREE_THRESHOLD:.0%} — "
              f"review {CALIBRATION_LOG_FILE} before finalising dataset.")
    return summary


# ── Main filter loop ──────────────────────────────────────────────────────────

def run_filter(mock: bool = True, verbose: bool = False, seed: int = 42,
               calibrate: bool = False):
    random.seed(seed)
    print(f"[judge_filter] seed={seed}  prompt=generation/prompts/judge_system_prompt.md")

    _exclude = {"filtered.jsonl", "judge_filter_log.jsonl"}
    raw_files = sorted(f for f in RAW_DIR.glob("*.jsonl") if f.name not in _exclude)

    all_tasks = []
    for fpath in raw_files:
        with open(fpath) as f:
            for line in f:
                line = line.strip()
                if line:
                    all_tasks.append(json.loads(line))

    print(f"\nJudge filter: {len(all_tasks)} raw tasks from {len(raw_files)} files")
    print(f"Mode: {'mock (heuristic)' if mock else 'live (LLM)'}")
    print(f"Filter threshold: mean judge score >= {FILTER_THRESHOLD}/5\n")

    passed, failed = [], []
    logs = []

    for task in all_tasks:
        judge_model = get_judge_model(task)
        scores = mock_judge(task) if mock else live_judge(task, judge_model)
        mean_score = sum(scores.values()) / len(scores)
        passed_filter = mean_score >= FILTER_THRESHOLD

        task["metadata"]["judge_model"]  = judge_model
        task["metadata"]["judge_scores"] = scores
        task["metadata"]["judge_mean"]   = round(mean_score, 3)

        log = {
            "task_id": task["task_id"],
            "authoring_mode": task["authoring_mode"],
            "generation_model": task["metadata"]["generation_model"],
            "judge_model": judge_model,
            "scores": scores,
            "mean": round(mean_score, 3),
            "passed": passed_filter,
        }
        logs.append(log)

        if passed_filter:
            passed.append(task)
        else:
            failed.append(task)

        if verbose:
            status = "✓" if passed_filter else "✗"
            print(f"  {status} {task['task_id']:10s}  mean={mean_score:.2f}  {scores}")

    # Write filtered tasks
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT_FILE, "w") as f:
        for task in passed:
            f.write(json.dumps(task) + "\n")

    # Write log
    with open(LOG_FILE, "w") as f:
        for log in logs:
            f.write(json.dumps(log) + "\n")

    print(f"\nResults:")
    print(f"  Total raw   : {len(all_tasks)}")
    print(f"  Passed filter: {len(passed)} ({len(passed)/len(all_tasks):.0%})")
    print(f"  Filtered out : {len(failed)}")
    print(f"  Written to  : {OUT_FILE}")

    # Mode breakdown
    modes = {}
    for t in passed:
        m = t["authoring_mode"]
        modes[m] = modes.get(m, 0) + 1
    print(f"  Mode breakdown: {modes}")

    # Optional eval-tier calibration spot-check
    if calibrate:
        run_calibration(passed, mock=mock, seed=seed)

    return passed, failed


def main():
    parser = argparse.ArgumentParser(description="LLM-as-a-judge task filter")
    parser.add_argument("--mock",      action="store_true", default=True)
    parser.add_argument("--live",      action="store_true", help="Overrides --mock")
    parser.add_argument("--verbose",   action="store_true")
    parser.add_argument("--calibrate", action="store_true",
                        help=f"After bulk filter, re-judge {CALIBRATION_SAMPLE_RATE:.0%} "
                             f"of passed tasks with eval-tier model ({EVAL_TIER_MODEL}) "
                             f"and log agreement. Flags run if agreement < "
                             f"{CALIBRATION_AGREE_THRESHOLD:.0%}.")
    parser.add_argument("--seed",    type=int, default=42,
                        help="Random seed for reproducibility (default: 42)")
    args = parser.parse_args()
    if args.live:
        args.mock = False
    run_filter(mock=args.mock, verbose=args.verbose, seed=args.seed,
               calibrate=args.calibrate)


if __name__ == "__main__":
    main()
